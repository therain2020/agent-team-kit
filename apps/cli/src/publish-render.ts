export interface PublishArtifact {
  artifactId: string;
  stageId: string;
  createdAt: string;
  text: string;
}

export interface PublishRun {
  runId: string;
  workflowId: string;
  status: string;
  createdAt: string;
  artifacts: PublishArtifact[];
}

export interface RenderedSite {
  index: string;
  pages: Record<string, string>;
}

export function renderSite(run: PublishRun): RenderedSite {
  const pages: Record<string, string> = {};
  const cards = run.artifacts
    .map((artifact) => {
      const file = `${fileName(artifact.artifactId)}.html`;
      pages[file] = renderArtifactPage(run, artifact);
      return `<a class="card" href="${escapeHtml(file)}">
  <span class="stage">${escapeHtml(artifact.stageId)}</span>
  <strong>${escapeHtml(artifact.artifactId)}</strong>
  <span class="meta">${escapeHtml(artifact.createdAt)}</span>
</a>`;
    })
    .join("\n");

  const index = page(
    run.runId,
    `<header>
  <p class="eyebrow">Agent Team Kit · published run</p>
  <h1>${escapeHtml(run.runId)}</h1>
  <p class="meta">workflow ${escapeHtml(run.workflowId)} · ${escapeHtml(run.status)} · ${escapeHtml(run.createdAt)}</p>
</header>
<section class="grid">${cards || "<p>No published artifacts.</p>"}</section>`,
  );

  return { index, pages };
}

function renderArtifactPage(
  run: PublishRun,
  artifact: PublishArtifact,
): string {
  return page(
    artifact.artifactId,
    `<nav><a href="index.html">← ${escapeHtml(run.runId)}</a></nav>
<header>
  <p class="eyebrow">${escapeHtml(artifact.stageId)}</p>
  <h1>${escapeHtml(artifact.artifactId)}</h1>
  <p class="meta">${escapeHtml(artifact.createdAt)}</p>
</header>
<pre>${escapeHtml(artifact.text)}</pre>`,
  );
}

function page(title: string, body: string): string {
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>${escapeHtml(title)} · Agent Team Kit</title>
<style>
  :root { color-scheme: dark; }
  body { margin: 0; padding: 48px 24px; background: #09090b; color: #e4e4e7; font: 14px/1.6 system-ui, -apple-system, "Segoe UI", sans-serif; }
  main { max-width: 860px; margin: 0 auto; }
  h1 { font-size: 22px; margin: 4px 0 8px; }
  .eyebrow { margin: 0; color: #a1a1aa; font-size: 11px; letter-spacing: .08em; text-transform: uppercase; }
  .meta { color: #71717a; font-size: 12px; margin: 0; }
  nav { margin-bottom: 24px; }
  a { color: #93c5fd; text-decoration: none; }
  .grid { display: grid; gap: 12px; margin-top: 28px; }
  .card { display: flex; flex-direction: column; gap: 2px; padding: 12px 14px; border: 1px solid #27272a; border-radius: 8px; color: #e4e4e7; }
  .card:hover { border-color: #52525b; }
  .stage { color: #71717a; font-size: 11px; text-transform: uppercase; letter-spacing: .06em; }
  pre { white-space: pre-wrap; word-break: break-word; background: #18181b; border: 1px solid #27272a; border-radius: 8px; padding: 16px; font: 13px/1.6 ui-monospace, monospace; }
  footer { margin-top: 40px; color: #52525b; font-size: 11px; }
</style>
</head>
<body>
<main>
${body}
<footer>Generated by Agent Team Kit · content is published as-is; scrub secrets before publishing.</footer>
</main>
</body>
</html>
`;
}

function fileName(artifactId: string): string {
  const cleaned = artifactId.replace(/[^a-zA-Z0-9_-]/g, "");
  return cleaned.length > 0 ? cleaned : "artifact";
}

function escapeHtml(value: string): string {
  return value
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;");
}
